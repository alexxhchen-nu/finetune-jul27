# 
# ## 17. 最重要的判断
# 
# 如果你的目标是：
# 
# ```text
# 让模型知道大量考古资料
# ```
# 
# 用 RAG。
# 
# 如果你的目标是：
# 
# ```text
# 让模型按你的考古流程工作
# ```
# 
# 用微调。
# 
# 如果你的目标是：
# 
# ```text
# 造一个全新的考古大模型
# ```
# 
# 通常不要做。
# 
# ---
# 
# ## 18. 最终原则
# 
# ```text
# 知识不要硬塞进模型参数。
# 知识放资料库。
# 方法用微调教。
# 规则写进 prompt。
# 引用靠 RAG 保证。
# ```
# 
# 这条路线最适合一个人做。

