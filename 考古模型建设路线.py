# 界面：Open WebUI
# ```
# 
# 更稳版本：
# 
# ```text
# 模型：Qwen2.5-14B-Instruct
# RAG：LlamaIndex / RAGFlow
# 向量库：Qdrant
# 微调：LLaMA-Factory / Unsloth
# 部署：vLLM
# 界面：Dify / 自己写 Web UI
# ```
