# %% [markdown]
# # 考古模型：直觉版路线
# 
# ## 一句话
# 
# 你要做的不是“从零训练一个新大模型”。
# 
# 你要做的是：
# 
# ```text
# 一个会按考古方法工作的模型
# +
# 一个能随时查考古资料的知识库
# ```
# 
# 更准确地说：
# 
# ```text
# 考古助手 = RAG 资料库 + 微调后的模型 + 证据规则 + 聊天界面
# ```
# 
# 用户感觉像“模型懂考古”。
# 
# 实际后台是：
# 
# ```text
# 模型先查资料，再按考古规则回答。
# ```
# 
# ---
# 
# ## 1. RAG 是什么
# 
# RAG 可以理解成：
# 
# ```text
# 给模型装一个可搜索的考古图书馆。
# ```
# 
# 模型本身不需要背下所有书。
# 
# 它回答问题前，系统自动去资料库里找相关内容。
# 
# 比如你问：
# 
# ```text
# M12 这座墓可能是什么年代？
# ```
# 
# 后台会自动找：
# 
# ```text
# M12 的原始描述
# M12 的出土器物
# M12 的地层关系
# 相关墓葬分期方法
# 相关器物类型学资料
# 术语表和证据规则
# ```
# 
# 然后再让模型回答。
# 
# 所以 RAG 的本质是：
# 
# ```text
# 知识不塞进模型脑子里，而是放在资料库里，让模型随用随查。
# ```
# 
# ---
# 
# ## 2. 微调是什么
# 
# 微调不是让模型背书。
# 
# 微调是教模型：
# 
# ```text
# 应该怎么做事。
# ```
# 
# 比如教它：
# 
# ```text
# 如何抽取墓葬信息
# 如何写遗址摘要
# 如何区分事实、推断、假设
# 如何列证据
# 如何避免乱断代
# 如何按你的格式输出
# ```
# 
# 微调后的模型更像一个受过训练的研究助理。
# 
# 它不一定知道所有资料。
# 
# 但它知道：
# 
# ```text
# 看到资料后应该怎么分析。
# ```
# 
# ---
# 
# ## 3. 训练模型是什么
# 
# 训练模型通常指从零造一个大模型。
# 
# 这需要：
# 
# ```text
# 海量文本
# 大量 GPU
# 分布式训练
# 模型架构
# tokenizer
# 安全对齐
# 评测体系
# 部署系统
# 很多钱和时间
# ```
# 
# 一个人通常不做这个。
# 
# 对你来说，训练模型不是第一选择。
# 
# 你的第一选择应该是：
# 
# ```text
# RAG + 微调
# ```
# 
# ---
# 
# ## 4. 三者的关系
# 
# 可以这样理解：
# 
# ```text
# RAG = 给模型资料
# 微调 = 教模型方法
# 训练 = 从零造模型
# ```
# 
# 对考古项目来说：
# 
# ```text
# 知识放 RAG
# 方法放微调
# 规则写 prompt
# ```
# 
# 这是最实用的组合。
# 
# ---
# 
# ## 5. 考古资料应该怎么分
# 
# 你的资料大致分成几类。
# 
# ### 事实资料
# 
# 这些放进 RAG：
# 
# ```text
# 发掘报告
# 考古简报
# 论文
# 墓葬表格
# 器物登记表
# 图版说明
# 地层记录
# 测年数据
# 遗址平面图说明
# 铭文释文
# ```
# 
# 它们回答：
# 
# ```text
# 有什么？在哪里？出土了什么？报告怎么说？
# ```
# 
# ### 方法资料
# 
# 这些也可以放进 RAG，也可以做成微调样本：
# 
# ```text
# 类型学方法
# 地层学原则
# 断代方法
# 器物分类规则
# 墓葬分期流程
# 考古报告写作规范
# 空间分析方法
# ```
# 
# 它们回答：
# 
# ```text
# 应该怎么判断？怎么分析？怎么写？
# ```
# 
# ### 术语表
# 
# 例如：
# 
# ```text
# 灰坑 / H
# 墓葬 / M
# 探方 / T
# 打破关系
# 叠压关系
# 随葬品组合
# 鬲、豆、罐、鼎、盉
# ```
# 
# 作用：
# 
# ```text
# 减少误读，统一词汇。
# ```
# 
# ### 证据规则
# 
# 这是最重要的。
# 
# 例如：
# 
# ```text
# 不能凭感觉断代
# 必须引用来源
# 不确定就标“待核”
# 地层关系优先于器物风格
# 冲突资料必须并列
# 区分原文事实和模型推断
# ```
# 
