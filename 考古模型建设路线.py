# ## 7. 元数据为什么重要
# 
# RAG 不是简单地把文本丢进去。
# 
# 每段资料最好带元数据。
# 
# 例如：
# 
# ```json
# {
#   "title": "XX遗址发掘报告",
#   "source_type": "excavation_report",
#   "site": "XX遗址",
#   "region": "河南",
#   "period": "战国",
#   "page": 123,
#   "feature_id": "M12",
#   "topic": ["墓葬", "陶器", "分期"]
# }
# ```
# 
# 没有元数据，模型很难知道：
# 
# ```text
# 这段话来自哪里
# 说的是哪个遗址
# 对应哪一页
# 是不是权威报告
# 和哪个墓葬有关
# ```
# 
# 考古研究里，出处非常重要。
# 
# 所以元数据不是装饰。
# 
# 它是证据链的一部分。
# 
# ---
# 
# ## 8. 实际工作流
# 
# 整体流程：
# 
# ```text
# PDF / Word / 图片
# ↓
# OCR 或 PDF 解析
# ↓
# 清洗文本
# ↓
# 按墓葬、器物、图版、表格行切片
# ↓
# 加元数据
# ↓
# 建向量索引
# ↓
# 用户提问
# ↓
# 系统检索相关资料
# ↓
# 模型按规则回答
# ```
# 
# ---
# 
# ## 9. 切片怎么切
# 
# 不要只按字数切。
# 
# 考古资料最好按研究对象切。
# 
# 例如：
# 
# ```text
# 一个墓葬一段
# 一个灰坑一段
# 一个器物描述一段
# 一个地层单位一段
# 一个图版说明一段
# 一个表格行一段
# ```
# 
# 因为你的问题通常是：
# 
# ```text
# M12 是什么？
# 这个器物属于哪类？
# 某遗址有哪些墓葬？
# 这组墓葬怎么分期？
# ```
# 
# 对象级切片比随机切片更好。
# 
# ---
# 
# ## 10. 微调样本长什么样
# 
# 微调样本不是整本书。
# 
# 微调样本是：
# 
# ```text
# 输入 → 理想输出
# ```
# 
# 例如：
# 
# ```json
# {
#   "instruction": "从考古报告段落中抽取墓葬信息。",
#   "input": "M12，竖穴土坑墓，墓向180°，出土陶鬲1、陶豆2、陶罐1。",
#   "output": {
#     "遗迹编号": "M12",
#     "墓葬形制": "竖穴土坑墓",
#     "墓向": "180°",
#     "随葬品": ["陶鬲", "陶豆", "陶罐"],
#     "年代判断": "资料不足，不能单独断代",
#     "证据": "原文仅提供形制、墓向和随葬品，缺少地层关系、图版比较或测年数据。"
#   }
# }
# ```
# 
# 再比如：
# 
# ```json
# {
#   "instruction": "判断下面考古论述中的事实、推断和假设。",
#   "input": "M8 出土陶鬲、豆、罐组合，可能属战国早期。",
#   "output": {
#     "事实": ["M8 出土陶鬲、豆、罐组合"],
#     "推断": ["可能属战国早期"],
#     "假设": [],
#     "不确定性": "未提供地层关系、图版比较或报告原始年代意见。"
#   }
# }
# ```
# 
# ---
# 
# ## 11. 微调适合教什么
# 
# 适合：
# 
# ```text
# 墓葬字段抽取
# 器物名称规范化
# 遗迹类型分类
# 事实/推断/假设分类
# 固定格式摘要
# 证据化回答格式
# 考古报告风格改写
# ```
# 
# 不适合：
# 
# ```text
# 记住几千篇报告
# 记住每一页内容
# 替代资料库
# 保证所有断代正确
# ```
# 
# ---
# 
# ## 12. 一个自然的最终体验
# 
# 用户只看到：
# 
# ```text
# 请分析 M12 的年代。
# ```
# 
# 系统后台做：
# 
# ```text
# 1. 查 M12 原文
# 2. 查同遗址相关墓葬
# 3. 查相关器物类型学资料
# 4. 查断代方法
# 5. 查证据规则
# 6. 让微调模型回答
# ```
# 
# 用户看到的答案像这样：
# 
# ```text
# M12 可暂按战国早期处理，但证据不足。
# 
# 依据：
# 1. 原报告记录 M12 为竖穴土坑墓。
# 2. 随葬品组合包括陶鬲、陶豆、陶罐。
# 3. 该组合与本区战国墓葬常见组合接近。
# 
# 不确定性：
# 1. 未见明确地层关系。
# 2. 未提供可复核图版比较。
# 3. 无测年数据。
# 
# 结论等级：初步判断，需复核。
# ```
# 
# 这就是你想要的“自然”。
# 
# 不是用户手动调用 RAG。
# 
# 而是系统默认自动检索。
# 
