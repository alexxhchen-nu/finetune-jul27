# ## 13. 常用模型选择
# 
# 一个人做中文考古，优先：
# 
# ```text
# Qwen2.5-7B-Instruct
# Qwen2.5-14B-Instruct
# Qwen3-8B
# Qwen3-14B
# ```
# 
# 机器一般：
# 
# ```text
# Qwen2.5-7B-Instruct + QLoRA
# ```
# 
# 显存好一点：
# 
# ```text
# Qwen2.5-14B-Instruct + QLoRA
# ```
# 
# 不建议一开始做：
# 
# ```text
# 70B 微调
# 从零训练
